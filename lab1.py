import time  # подключаем модуль времени: нужен для пауз time.sleep()
import os  # подключаем модуль работы с ОС: нужен для os.system("clear")

# Задание 1. Флаг страны 

RESET = "\033[0m"  # escape-код сброса цвета: после него вывод снова обычного цвета


def print_finland_flag():  # объявляем функцию, которая рисует флаг Финляндии

    WHITE = "\033[107m"  # ярко-белый фон
    BLUE = "\033[44m"    # синий фон
 
    rows, cols = 11, 18  # размер флага в ячейках: 11 строк и 18 столбцов
    # Строки/столбцы, попадающие в перекладины креста (включительно)
    cross_row_start, cross_row_end = 4, 6  # номера строк горизонтальной перекладины креста
    cross_col_start, cross_col_end = 5, 6  # номера столбцов вертикальной перекладины креста
 
    print("=== Задание 1: флаг Финляндии ===")  # печатаем заголовок задания
    for r in range(rows):  # цикл по строкам флага, r - номер строки
        line = ""  # пустая строка, в которую соберём одну строку флага
        for c in range(cols):  # цикл по столбцам, c - номер столбца
            # ячейка синяя, если она лежит в горизонтальной ИЛИ вертикальной перекладине креста, иначе - белая
            in_cross = (cross_row_start <= r <= cross_row_end) or (cross_col_start <= c <= cross_col_end)  # True, если ячейка в кресте
            line += (BLUE if in_cross else WHITE) + "  "  # добавляем ячейку: цвет фона (синий или белый) и два пробела
        print(line + RESET)  # печатаем строку флага и сбрасываем цвет
    print()  # пустая строка-отступ после флага


print_finland_flag()  # вызываем функцию: флаг выводится на экран

# Задание 2. Узор
def print_pattern_i():  # объявляем функцию, которая рисует узор i (ряд кругов)

    CIRCLES = 2  # сколько кругов в строке
    RADIUS = 4  # радиус круга в ячейках

    BLACK = "\033[40m"    # чёрный фон ячейки (внутри круга)
    WHITE = "\033[107m"   # белый фон ячейки (снаружи круга)
    CELL = "  "  # одна ячейка = два пробела (получается примерно квадрат)

    diameter = 2 * RADIUS + 1   # ширина и высота одного круга в ячейках

    print("=== Задание 2: узор (вариант i) ===")  # печатаем заголовок задания
    for row in range(diameter):  # цикл по строкам узора, row - номер строки
        line = ""  # пустая строка, в которую соберём одну строку узора
        for _ in range(CIRCLES):  # цикл по кругам; номер круга не нужен, поэтому имя _
            for col in range(diameter):  # цикл по ячейкам внутри одного круга, col - номер столбца
                dx = col - RADIUS  # смещение ячейки от центра круга по горизонтали
                dy = row - RADIUS  # смещение ячейки от центра круга по вертикали
                if dx * dx + dy * dy <= (RADIUS + 0.5) ** 2:  # ячейка внутри круга (уравнение окружности)
                    line = line + BLACK + CELL  # добавляем чёрную ячейку
                else:  # иначе ячейка снаружи круга
                    line = line + WHITE + CELL  # добавляем белую ячейку
        print(line + RESET)  # печатаем строку узора и сбрасываем цвет
    print()  # пустая строка-отступ после узора


print_pattern_i()  # вызываем функцию: узор выводится на экран

# Задание 3. Анимация
def animate():  # объявляем функцию анимации: заполнение шкалы в процентах

    PAUSE_BEFORE = 3                 # пауза перед анимацией, сек
    FRAME_DELAY = 1                  # сколько секунд показывается один кадр
    ROW = 5                          # номер строки экрана, в которой рисуется шкала
    BAR_WIDTH = 40                   # длина шкалы в символах
    PERCENTS = [25, 50, 75, 100]     # проценты по кадрам (4 числа = 4 кадра)

    HIDE_CURSOR = "\033[?25l"  # escape-код: спрятать курсор
    SHOW_CURSOR = "\033[?25h"  # escape-код: показать курсор
    WHITE_BG = "\033[107m"           # белый фон (заполненная часть шкалы)
    WHITE_TEXT = "\033[97m"          # белый цвет текста (число процентов)
    CLEAR_ALL = "\033[2J\033[3J\033[H"   # стереть экран, стереть историю прокрутки, курсор в начало

    time.sleep(PAUSE_BEFORE)  # ждём 3 секунды, чтобы успеть рассмотреть флаг и узор
    print(HIDE_CURSOR, end="")  # прячем курсор; end="" - не переводить строку после печати

    frame_number = 1  # номер текущего кадра, нужен для подписи "Кадр N из 4"
    for percent in PERCENTS:  # цикл по кадрам: percent поочерёдно равен 25, 50, 75, 100
        os.system("clear")  # очищаем консоль командой ОС
        print(CLEAR_ALL, end="") #стереть экран  # дополнительно стираем экран и историю прокрутки escape-кодами

        print("\033[1;1H" + "Кадр " + str(frame_number) + " из " + str(len(PERCENTS)))  # курсор в начало экрана и подпись "Кадр N из 4"

        filled = BAR_WIDTH * percent // 100  # сколько символов шкалы закрасить (// - деление без дробной части)
        empty = BAR_WIDTH - filled  # сколько символов шкалы остаётся пустыми
        bar = "[" + WHITE_BG + " " * filled + RESET + " " * empty + "]"  # собираем шкалу: рамка, белая часть, сброс цвета, пустая часть, рамка

        print("\033[" + str(ROW) + ";1H" + bar + " " + WHITE_TEXT + str(percent) + "%" + RESET)  # курсор в строку ROW, печать шкалы и числа процентов белым цветом
        
        time.sleep(FRAME_DELAY)  # держим кадр на экране FRAME_DELAY секунд
        frame_number = frame_number + 1  # увеличиваем номер кадра на 1

    print("\033[" + str(ROW + 2) + ";1H" + SHOW_CURSOR + "Загрузка завершена")  # курсор на две строки ниже шкалы, показываем курсор, пишем сообщение
    print()  # пустая строка-отступ

animate()  # вызываем функцию: запускается анимация

# Задание 4. Диаграмма
def print_percentage_diagram():  # объявляем функцию диаграммы по данным из файла

    FILE_NAME = "sequence.txt"  # имя файла с числами
    A_MIN = 5  # группа A: нижняя граница диапазона
    A_MAX = 10  # группа A: верхняя граница диапазона
    B_MIN = -10  # группа B: нижняя граница диапазона
    B_MAX = -5  # группа B: верхняя граница диапазона
    BAR_WIDTH = 40  # длина диаграммы в символах
    BAR_HEIGHT = 1  # высота диаграммы в строках


    GREEN_BG = "\033[42m"        # зелёный фон (группа A)
    RED_BG = "\033[41m"          # красный фон (группа B)

    print("=== Задание 4: диаграмма по sequence.txt ===")  # печатаем заголовок задания

    file = open(FILE_NAME)  # открываем файл для чтения (ищется в папке, из которой запущена программа)

    count_a = 0  # счётчик чисел группы A
    count_b = 0  # счётчик чисел группы B
    for line in file:  # цикл по строкам файла: line - одна строка, то есть одно число
        line = line.strip()  # убираем перевод строки и пробелы по краям
        if line == "":  # если строка оказалась пустой
            continue  # пропускаем её и переходим к следующей строке файла
        number = float(line)  # переводим текст строки в число
        if A_MIN <= number <= A_MAX:  # число попало в диапазон группы A?
            count_a = count_a + 1  # да: увеличиваем счётчик группы A
        elif B_MIN <= number <= B_MAX:  # иначе: число попало в диапазон группы B?
            count_b = count_b + 1  # да: увеличиваем счётчик группы B
    file.close()  # закрываем файл; остальные числа отброшены

    total = count_a + count_b  # сумма двух количеств, она принимается за 100%
    if total == 0:  # защита от деления на ноль: нет ни одного подходящего числа
        print("В файле нет чисел из заданных диапазонов.")  # сообщаем об этом
        return  # выходим из функции
    percent_a = count_a * 100 / total  # доля группы A в процентах
    percent_b = 100 - percent_a  # доля группы B: остаток до 100%

    len_a = round(BAR_WIDTH * percent_a / 100)  # длина зелёной части диаграммы в символах
    len_b = BAR_WIDTH - len_a  # длина красной части: остаток до полной ширины

    bar = GREEN_BG + " " * len_a + RED_BG + " " * len_b + RESET  # собираем полосу: зелёная часть, красная часть, сброс цвета
    for row in range(BAR_HEIGHT):  # повторяем BAR_HEIGHT раз
        print(bar)  # печатаем полосу диаграммы
    print()  # пустая строка-отступ
    
    print(GREEN_BG + "  " + RESET + " числа от " + str(A_MIN) + " до " + str(A_MAX)  # подпись группы A: зелёный квадрат и диапазон
          + ": " + str(count_a) + " шт. - " + str(round(percent_a, 2)) + "%")  # количество чисел и процент, округлённый до 2 знаков
    print(RED_BG + "  " + RESET + " числа от " + str(B_MIN) + " до " + str(B_MAX)  # подпись группы B: красный квадрат и диапазон
          + ": " + str(count_b) + " шт. - " + str(round(percent_b, 2)) + "%")  # количество чисел и процент, округлённый до 2 знаков
    print()  # пустая строка-отступ

print_percentage_diagram()  # вызываем функцию: диаграмма выводится на экран

# Дополнительное задание. График
def build_function_graph():  # объявляем функцию, которая строит график y = x / 2

    X_MAX = 16     # правая граница по x

    GRAY_BG = "\033[100m"  # серый фон (для осей)
    GREEN_BG = "\033[42m"  # зелёный фон (для линии графика)

    EMPTY_CELL = "  "  # пустая ячейка: два обычных пробела
    AXIS_CELL = GRAY_BG + "  " + RESET  # ячейка оси: два пробела на сером фоне
    LINE_CELL = GREEN_BG + "  " + RESET  # ячейка линии графика: два пробела на зелёном фоне

    y_max = int(X_MAX / 2)  # наибольшее значение y; int() отбрасывает дробную часть
    height = y_max + 1  # число строк графика: значения y от 0 до y_max включительно
    width = X_MAX + 1  # число столбцов графика: значения x от 0 до X_MAX включительно

    grid = []  # таблица ячеек графика, пока пустая
    for r in range(height):  # цикл по строкам таблицы
        row = []  # новая пустая строка таблицы
        for c in range(width):  # цикл по столбцам таблицы
            row.append(EMPTY_CELL)  # кладём в строку пустую ячейку
        grid.append(row)  # добавляем готовую строку в таблицу

    for c in range(width):  # цикл по столбцам нижней строки
        grid[height - 1][c] = AXIS_CELL  # красим нижнюю строку: это ось X
    for r in range(height):  # цикл по строкам левого столбца
        grid[r][0] = AXIS_CELL  # красим левый столбец: это ось Y

    for x in range(1, width):  # цикл по x от 1 до X_MAX (x = 0 занят осями)
        y = x / 2  # значение функции y = x / 2
        y_cell = int(y + 0.5)  # округляем y до целого, половина округляется вверх
        row = height - 1 - y_cell  # номер строки таблицы: y = 0 внизу, большие y выше
        grid[row][x] = LINE_CELL  # красим ячейку линии графика

    picture = ""  # итоговая строка с картинкой графика, пока пустая
    for r in range(height):  # цикл по строкам таблицы
        for c in range(width):  # цикл по ячейкам строки
            picture = picture + grid[r][c]  # приклеиваем ячейку к картинке
        picture = picture + "\n"  # в конце строки таблицы ставим перевод строки

    print("=== Допзадание: график y = x/2 ===")  # печатаем заголовок
    print(picture)  # выводим всю картинку графика одним вызовом print

build_function_graph()  # вызываем функцию: график выводится на экран